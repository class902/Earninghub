import { z } from 'zod';
import { zite } from 'zitejs/db';
import { createEndpoint } from 'zitejs/backend';

const CONFIG_KEY = '__config__';

export default createEndpoint({
  description: 'Get public site settings',
  inputSchema: z.object({}),
  outputSchema: z.object({
    googleFormUrl: z.string(),
    googleFormLabel: z.string(),
    googleFormEnabled: z.boolean(),
    leadFieldsConfig: z.string(),
    wifiWarningBannerUrl: z.string(),
    promoEnabled: z.boolean(),
    promoBannerUrl: z.string(),
    promoTitle: z.string(),
    promoSubtitle: z.string(),
    promoButtonText: z.string(),
    promoOfferLink: z.string(),
    promoRedirectLink: z.string(),
    promoCashbackFormEnabled: z.boolean(),
    telegramLink: z.string(),
    supportEmail: z.string(),
    webLogoUrl: z.string(),
    socialLinksJson: z.string(),
    referralEnabled: z.boolean(),
    referralBonusYou: z.number(),
    referralBonusFriend: z.number(),
    referralTerms: z.string(),
    referralMinOffers: z.number(),
    globalActionButtonsJson: z.string(),
    trackByUpi: z.boolean(),
    trackByName: z.boolean(),
    trackByMobile: z.boolean(),
    trackByEmail: z.boolean(),
    statusCtaConfigJson: z.string(),
    statusLabelsJson: z.string(),
    showStatusHistoryDefault: z.boolean(),
    statusHistoryMode: z.string(),
    leadTrackDefaultFilter: z.string(),
    payoutConfigJson: z.string(),
    dashboardCustomJson: z.string(),
    siteName: z.string(),
    faviconUrl: z.string(),
    themeConfig: z.string(),
    layoutConfig: z.string(),
    seoTitle: z.string(),
    seoDescription: z.string(),
    gaId: z.string(),
    fontFamily: z.string(),
    tickerText: z.string(),
    customDomain: z.string(),
    notificationEmail: z.string(),
    whatsappLink: z.string(),
    // Lead tag options (Customer Type & App Source)
    leadTagOptionsJson: z.string(),
    // Promo timing
    promoDelay: z.number(),
    promoAutoClose: z.number(),
    // Site links custom
    siteLinksCustomJson: z.string(),
    uiConfigJson: z.string(),
    // Config metadata
    configVersion: z.number(),
    lastSavedAt: z.string(),
  }),
  execute: async () => {
    const defaults = {
      googleFormUrl: '', googleFormLabel: 'Apply Now', googleFormEnabled: false, leadFieldsConfig: '',
      wifiWarningBannerUrl: '', promoEnabled: false, promoBannerUrl: '',
      promoTitle: '', promoSubtitle: '', promoButtonText: 'Claim Now →',
      promoOfferLink: '', promoRedirectLink: '',
      promoCashbackFormEnabled: false, telegramLink: '', supportEmail: '',
      webLogoUrl: '', socialLinksJson: '[]', referralEnabled: false,
      referralBonusYou: 50, referralBonusFriend: 25, referralTerms: '',
      referralMinOffers: 1, globalActionButtonsJson: '[]',
      trackByUpi: true, trackByName: true, trackByMobile: true, trackByEmail: false, statusCtaConfigJson: '{}',
      statusLabelsJson: '{}', showStatusHistoryDefault: true,
      statusHistoryMode: 'show', leadTrackDefaultFilter: '7d',
      payoutConfigJson: '{}', dashboardCustomJson: '{}',
      siteName: '', faviconUrl: '', themeConfig: '{}', layoutConfig: '{}',
      seoTitle: '', seoDescription: '', gaId: '', fontFamily: '', tickerText: '', customDomain: '',
      notificationEmail: '', whatsappLink: '', leadTagOptionsJson: '{}',
      promoDelay: 3, promoAutoClose: 0,
      siteLinksCustomJson: '[]',
      uiConfigJson: '{}',
      configVersion: 0,
      lastSavedAt: '',
    };
    const config = await zite.posters.findOne({ filters: { title: CONFIG_KEY } });
    if (!config?.imageUrl) return defaults;
    try {
      const s = JSON.parse(config.imageUrl);
      let statusHistoryMode = s.statusHistoryMode || '';
      if (!statusHistoryMode) {
        statusHistoryMode = s.showStatusHistoryDefault === false ? 'collapsed' : 'show';
      }
      return {
        googleFormUrl: s.googleFormUrl || '',
        googleFormLabel: s.googleFormLabel || 'Apply Now',
        googleFormEnabled: Boolean(s.googleFormEnabled),
        leadFieldsConfig: s.leadFieldsConfig || '',
        wifiWarningBannerUrl: s.wifiWarningBannerUrl || '',
        promoEnabled: Boolean(s.promoEnabled),
        promoBannerUrl: s.promoBannerUrl || '',
        promoTitle: s.promoTitle || '',
        promoSubtitle: s.promoSubtitle || '',
        promoButtonText: s.promoButtonText || 'Claim Now →',
        promoOfferLink: s.promoOfferLink || '',
        promoRedirectLink: s.promoRedirectLink || '',
        promoCashbackFormEnabled: Boolean(s.promoCashbackFormEnabled),
        telegramLink: s.telegramLink || '',
        supportEmail: s.supportEmail || '',
        webLogoUrl: s.webLogoUrl || '',
        socialLinksJson: s.socialLinksJson || '[]',
        referralEnabled: Boolean(s.referralEnabled),
        referralBonusYou: typeof s.referralBonusYou === 'number' ? s.referralBonusYou : 50,
        referralBonusFriend: typeof s.referralBonusFriend === 'number' ? s.referralBonusFriend : 25,
        referralTerms: s.referralTerms || '',
        referralMinOffers: typeof s.referralMinOffers === 'number' ? s.referralMinOffers : 1,
        globalActionButtonsJson: s.globalActionButtonsJson || '[]',
        trackByUpi: typeof s.trackByUpi === 'boolean' ? s.trackByUpi : true,
        trackByName: typeof s.trackByName === 'boolean' ? s.trackByName : true,
        trackByMobile: typeof s.trackByMobile === 'boolean' ? s.trackByMobile : true,
        trackByEmail: typeof s.trackByEmail === 'boolean' ? s.trackByEmail : false,
        statusCtaConfigJson: s.statusCtaConfigJson || '{}',
        statusLabelsJson: s.statusLabelsJson || '{}',
        showStatusHistoryDefault: statusHistoryMode === 'show',
        statusHistoryMode,
        leadTrackDefaultFilter: s.leadTrackDefaultFilter || '7d',
        payoutConfigJson: s.payoutConfigJson || '{}',
        dashboardCustomJson: s.dashboardCustomJson || '{}',
        siteName: s.siteName || '',
        faviconUrl: s.faviconUrl || '',
        themeConfig: s.themeConfig || '{}',
        layoutConfig: s.layoutConfig || '{}',
        seoTitle: s.seoTitle || '',
        seoDescription: s.seoDescription || '',
        gaId: s.gaId || '',
        fontFamily: s.fontFamily || '',
        tickerText: s.tickerText || '',
        customDomain: s.customDomain || '',
        notificationEmail: s.notificationEmail || '',
        whatsappLink: s.whatsappLink || '',
        leadTagOptionsJson: s.leadTagOptionsJson || '{}',
        promoDelay: typeof s.promoDelay === 'number' ? s.promoDelay : 3,
        promoAutoClose: typeof s.promoAutoClose === 'number' ? s.promoAutoClose : 0,
        siteLinksCustomJson: s.siteLinksCustomJson || '[]',
        uiConfigJson: s.uiConfigJson || '{}',
        configVersion: typeof s.configVersion === 'number' ? s.configVersion : 0,
        lastSavedAt: s.lastSavedAt || '',
      };
    } catch {
      return defaults;
    }
  },
});
